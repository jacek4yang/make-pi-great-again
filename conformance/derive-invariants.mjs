#!/usr/bin/env node
// Derives conformance/invariants.json from the canonical OWNERSHIP map in
// lib.mjs. invariants.json is a GENERATED view — never hand-edit it; the
// executable truth is the exact bracket-tag ownership in lib.mjs, enforced
// by run-conformance.mjs against the manifests.
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { OWNERSHIP, canonicalInvariantSetName } from "./lib.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const metaRoot = resolve(here, "..");

const invariants = {};
for (const [id, repo] of Object.entries(OWNERSHIP)) {
  invariants[id] = { repo, test: `exact [${id}] bracket tag (enforced by run-conformance.mjs)` };
}
const doc = {
  $comment:
    "GENERATED by conformance/derive-invariants.mjs from lib.mjs OWNERSHIP — the canonical source. " +
    "The runner matches tests by exact [ID] bracket tags; regex mapping is retired.",
  invariants,
  canonicalSet: canonicalInvariantSetName(),
};
writeFileSync(join(metaRoot, "conformance", "invariants.json"), JSON.stringify(doc, null, 2) + "\n");
console.log(`invariants.json derived: ${canonicalInvariantSetName()}`);
